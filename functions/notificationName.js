//
// そらもよう Cloud Functions — 通知の文で人を呼ぶ形の純粋関数 ⭐️
//
// 名前がある人は「○○さん」、名前が無い人は「空が好きなだれか」（「さん」を付けない）。
// 2026-10-25 利用者の決定。アプリの他人のプロフィールの題（iOS の ProfileOwnerName.fallback・1.18.0 PR-B #209）と
// 同じ言葉・同じ考え（名前が無い人には「さん」を付けない）。
// 使う所: index.js（いいね・コメント・新着投稿・フォロー）・recommendationCore.js（おすすめの空）・
// soratomoCore.js（そらともの新着投稿・リアクション）。呼び方を変えるときはここだけを直す。
//
// ⚠️ 「名前が無い」の判定は呼び出し側に残す（index.js は値があるか・そらともの新着投稿は空文字か・
//    リアクションは空白だけも無いとみなす＝それぞれ意図して分けてある）。この部品は判定の済んだ名前を受け取るだけ。
//

"use strict";

/** 表示名が無い人を通知の文で呼ぶ言葉（「さん」を付けずにそのまま主語にする） */
const FALLBACK_NAME = "空が好きなだれか";

/**
 * 通知の文の主語になる呼び方。
 * 使い方: `${callName(name)}があなたをフォローしました` →「そらさんがあなたをフォローしました」
 *         /「空が好きなだれかがあなたをフォローしました」
 * @param {unknown} name 表示名。呼び出し側で「名前が無い」と判定したら空文字を渡す
 * @returns {string} 「○○さん」または「空が好きなだれか」
 */
function callName(name) {
  return name ? `${name}さん` : FALLBACK_NAME;
}

module.exports = {
  FALLBACK_NAME,
  callName,
};
